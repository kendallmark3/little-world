// INTENT-002 evidence: runs the initial experiment headless and writes what actually happened.
// Usage: node scripts/agent-experiment.mjs [--write]   (with --write: docs/agent-world-evidence.md)
import { writeFileSync } from 'node:fs';
import { createAgentSim, step, metrics, formatSimTime } from '../src/agentworld/sim.js';
import { CONFIGS, TICKS_PER_MINUTE } from '../src/agentworld/rules.js';
import { structById } from '../src/agentworld/world.js';

const TEN = 10 * TICKS_PER_MINUTE;
const SEEDS = [42, 7, 99, 2026, 314];
const out = [];
const p = (s = '') => out.push(s);

function runExperiment(seed, cfg, capture = false) {
  const sim = createAgentSim(seed, cfg);
  const decisions = [];
  if (capture) {
    sim.onDecision = (agent, d, per) => decisions.push({
      tick: sim.state.tick, agent: agent.name, agentId: agent.id, role: agent.role, strategy: agent.strategy,
      x: Math.round(agent.x), y: Math.round(agent.y), observations: per.observations, signals: per.signals.slice(0, 6),
      structures: per.structures.map((s) => s.name), decision: structuredClone(d),
    });
  }
  const t0 = performance.now();
  for (let i = 0; i < TEN; i++) step(sim);
  return { sim, m: metrics(sim.state), ms: performance.now() - t0, decisions };
}

const t0 = performance.now();
p('# Agent World — INTENT-002 evidence');
p();
p(`Generated by \`node scripts/agent-experiment.mjs --write\`. Every number and trace below comes from a real run of the simulation in \`src/agentworld/\`; nothing is hand-written.`);
p();
p('## The initial experiment: ten agents, ten simulated minutes, no central coordinator');
p();
const headers = ['World', 'Seed', 'Structures', 'Links', 'Reliability', 'Useful work (s)', 'Wasted (s)', 'Compute spent', 'Compute left', 'Coop', 'Comp', 'Defects found / prod', 'Repaired', 'Reuse', 'Run time'];
p(`| ${headers.join(' | ')} |`);
p(`|${headers.map(() => '---').join('|')}|`);
const agg = {};
for (const cfg of Object.keys(CONFIGS)) {
  agg[cfg] = [];
  for (const seed of SEEDS) {
    const { m, ms } = runExperiment(seed, cfg);
    agg[cfg].push(m);
    p(`| ${CONFIGS[cfg].label} | ${seed} | ${m.completed} | ${m.connections} | ${Math.round(m.reliability * 100)}% | ${m.usefulWork} | ${m.wastedWork} | ${m.computeSpent} | ${m.compute} | ${m.cooperation} | ${m.competition} | ${m.defectsFound} / ${m.defectsSurfaced} | ${m.defectsRepaired} | ${m.reuses} | ${Math.round(ms)} ms |`);
  }
}
p();
p('Averages over the five seeds:');
p();
p('| World | Structures | Reliability | Useful work (s) | Compute left | Cooperation | Competition | Defects repaired |');
p('|---|---|---|---|---|---|---|---|');
const avg = (arr, f) => arr.reduce((a, b) => a + f(b), 0) / arr.length;
for (const cfg of Object.keys(CONFIGS)) {
  const a = agg[cfg];
  p(`| ${CONFIGS[cfg].label} | ${avg(a, (m) => m.completed).toFixed(1)} | ${Math.round(avg(a, (m) => m.reliability) * 100)}% | ${Math.round(avg(a, (m) => m.usefulWork))} | ${Math.round(avg(a, (m) => m.compute))} | ${avg(a, (m) => m.cooperation).toFixed(1)} | ${avg(a, (m) => m.competition).toFixed(1)} | ${avg(a, (m) => m.defectsRepaired).toFixed(1)} |`);
}
p();
p('These are outcomes, not settings. Cooperative agents are never told to succeed; competitive agents are never told to fail. The differences come from what each strategy weighs in its own utility calculation (see `src/agentworld/decision.js`).');
p();

// ---------------------------------------------------------------------------
const main = runExperiment(42, 'mixed', true);
const s = main.sim.state;

p('## Example agent decision trace (Mixed World, seed 42)');
p();
const arch = main.decisions.find((d) => d.role === 'Architect' && d.decision.candidates.filter((c) => c.valid).length >= 4 && ['connect', 'review', 'design'].includes(d.decision.chosen.action) && d.observations.some((o) => /isolated/.test(o)))
  || main.decisions.find((d) => d.role === 'Architect' && d.decision.candidates.filter((c) => c.valid).length >= 4);
const trace = (d) => {
  p(`**${d.agent}** (${d.role}, ${d.strategy}) at ${formatSimTime(d.tick)}, standing at (${d.x}, ${d.y}).`);
  p();
  p('*Observe* — what it perceived:');
  for (const o of d.observations) p(`- ${o}`);
  p(`- Signals: ${d.signals.map((g) => `${g.label} ${g.perceived}${g.flaggedBy ? ' 🚩' : ''} @ ${g.dist} tiles`).join('; ') || 'none'}`);
  p();
  p('*Evaluate* — every option it scored (utility = sum of the terms):');
  p();
  p('| | Option | Target | Terms | Utility | p |');
  p('|---|---|---|---|---|---|');
  for (const c of d.decision.candidates) {
    p(`| ${c.chosen ? '✓' : ''} | ${c.label} | ${c.target || ''} | ${c.valid ? c.terms.map(([k, v]) => `${k} ${v}`).join(', ') : `not possible: ${c.invalid}`} | ${c.valid ? c.utility : '—'} | ${c.valid ? c.prob : ''} |`);
  }
  p();
  p(`*Decide* — ${d.decision.reason}`);
  p();
};
if (arch) trace(arch);

// Same world, different minds: an Architect and a Developer deciding moments apart.
p('## Same world, different perceptions');
p();
let pair = null;
for (const a of main.decisions.filter((d) => d.role === 'Architect')) {
  const dv = main.decisions.find((d) => d.role === 'Developer' && Math.abs(d.tick - a.tick) <= 6 && d.structures.filter((n) => a.structures.includes(n)).length >= 3 && d.decision.chosen.action !== a.decision.chosen.action && !['rest', 'wander'].includes(d.decision.chosen.action) && !['rest', 'wander'].includes(a.decision.chosen.action));
  if (dv) { pair = [a, dv]; break; }
}
if (pair) {
  const shared = pair[1].structures.filter((n) => pair[0].structures.includes(n));
  p(`At ${formatSimTime(pair[0].tick)}–${formatSimTime(pair[1].tick)} both could see ${shared.join(', ')}.`);
  p();
  for (const d of pair) {
    const top = d.decision.candidates.filter((c) => c.valid).slice(0, 4).map((c) => `${c.label.toLowerCase()} → ${c.target} (${c.utility})`).join('; ');
    p(`- **${d.agent}** (${d.strategy}) weighed: ${top}. Chose **${d.decision.chosen.label.toLowerCase()} → ${d.decision.chosen.target}**.`);
  }
  p();
  p('Different capabilities and strategy weights turn the same surroundings into different decisions.');
  p();
}

// ---------------------------------------------------------------------------
p('## Example emergent coordination sequence');
p();
// The structure whose story involved the most different agents.
const involved = new Map();
for (const e of s.log) {
  if (!e.structId || !e.agentId) continue;
  const st = structById(s, e.structId);
  if (!st || st.type === 'connection') continue;
  if (!involved.has(st.id)) involved.set(st.id, new Set());
  involved.get(st.id).add(e.agentId);
}
const best = [...involved.entries()].sort((a, b) => b[1].size - a[1].size)[0];
if (best) {
  const st = structById(s, best[0]);
  p(`**${st.name}** — ${best[1].size} different agents acted on it, and none of them was assigned to it:`);
  p();
  for (const e of s.log.filter((x) => x.structId === st.id || (x.text.includes(st.name) && x.kind !== 'discover'))) p(`- \`${formatSimTime(e.tick)}\` ${e.text}`);
  p();
  // Show the decision that picked it up from the environment.
  const pick = main.decisions.find((d) => d.decision.chosen.target === st.name && d.decision.candidates.some((c) => c.chosen && c.terms.some(([k]) => k.startsWith('finish others'))))
    || main.decisions.find((d) => d.decision.chosen.target === st.name && d.agentId !== st.ownerId);
  if (pick) {
    const c = pick.decision.candidates.find((x) => x.chosen);
    p(`The pick-up was ${pick.agent}'s own decision at ${formatSimTime(pick.tick)}: it perceived a **${c.signalKind}** signal from ${st.name} and scored *${c.label.toLowerCase()}* at ${c.utility} (${c.terms.map(([k, v]) => `${k} ${v}`).join(', ')}). That signal existed only because another agent had changed the environment.`);
    p();
  }
}

// Stigmergy counts
const stig = main.decisions.filter((d) => {
  const c = d.decision.candidates.find((x) => x.chosen);
  return c && ['construction', 'failure', 'verification', 'integration', 'reuse', 'complexity', 'stale', 'optimization'].includes(c.signalKind);
});
const flagged = main.decisions.filter((d) => d.decision.candidates.find((x) => x.chosen)?.terms.some(([k]) => k === 'flagged by explorer'));
p(`Across the run, **${stig.length} of ${main.decisions.length} decisions** (${Math.round((stig.length / main.decisions.length) * 100)}%) chose an action in response to a signal left by another agent's work (unfinished builds, defects, untested or isolated structures, libraries). ${flagged.length} decisions were influenced by an Explorer's flag. ${s.counters.handoffs} times an agent finished construction someone else had started.`);
p();
p(`Ten simulated minutes of all three worlds × five seeds ran in ${Math.round(performance.now() - t0)} ms total.`);

const text = out.join('\n') + '\n';
if (process.argv.includes('--write')) { writeFileSync(new URL('../docs/agent-world-evidence.md', import.meta.url), text); console.log('wrote docs/agent-world-evidence.md'); }
else console.log(text);
